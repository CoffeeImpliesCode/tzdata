/// `extern` declarations the provider may legitimately not export.
///
/// This SDK declares none, and the reason is structural rather than a
/// statement of intent: every `extern` the aggregate header declares is
/// selected by a macro that the same build also gives the C compiler, so
/// "declared in the translation" and "emitted by the object" are the same
/// condition by construction. `build.zig` reads one `translated_macros` table
/// to drive all three of the translation, the pkg-config metadata and the
/// Windows export list, so the four names cannot describe different libraries:
///
///   * `HAVE_STRFTIME_L` selects `tz_strftime_l` (`strftime.c:175`);
///   * `SUPPORT_POSIX2008` selects `tz_asctime_r` and `tz_ctime_r`; without it
///     `asctime.c:53-62` renames both to static functions and tzcode emits
///     neither;
///   * `HAVE_TZNAME` selects `tz_tzname` (`localtime.c:623-625`);
///   * `USG_COMPAT` selects `tz_timezone` and `tz_daylight`
///     (`localtime.c:626-629`).
///
/// A provider built with different values for those four macros is a provider
/// for a different declaration list, and `load` reports the missing symbol by
/// name - which is the correct outcome, not something to paper over with an
/// `optional` entry. Marking one optional would not help anyway: an `extern`
/// left direct has nothing to resolve against, because the whole point of the
/// runtime route is that nothing is linked, and an optional one stops the
/// program by name at the first call. It is spelled out so that adding a
/// header with a genuinely optional entry point is a build-file change with a
/// name in it.
const provider_optional = "";

/// `extern` declarations this build does not require from a provider.
///
/// None. Every function the selected header declares is expected from a
/// provider, and a provider that does not export one of them is refused rather
/// than half used. In particular this is where the POSIX surface -
/// `tz_localtime`, `tz_mktime`, `tz_tzset`, `tz_ctime`, `tz_asctime` and
/// `tz_strftime` - stays routed: those are the names that write the exported
/// globals `tz_tzname`, `tz_timezone` and `tz_daylight`
/// (`localtime.c:702-715`), and a caller that reaches them through the table is
/// reaching the provider's own state. A name here would be routed into a
/// nullable table field instead: its absence would not fail the load, and its
/// wrapper would stop the program by name. Only `libc_noise` above keeps a
/// declaration direct.
const provider_excluded = "";

/// The loader core, for a *linked* build to import.
///
/// A linked build has no dispatch, so the facade needs the core module itself
/// for the two public types `LoadSource` and `LoadError`: they are this SDK's
/// types and they must be the same types a caller names in either configuration.
/// It costs a linked build two declarations and no code, since nothing else in
/// that module is referenced until a configuration actually instantiates the
/// loader.
///
/// A runtime-loading build must *not* import this separately: `createModule`
/// makes the one core instance the dispatch uses, and the dispatch re-exports
/// the two types from it. Two instances would be two sets of types, and a
/// consumer would be naming one while `load` expects the other.
pub fn createCoreModule(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    return b.createModule(.{
        .root_source_file = b.path("runtime/loader.zig"),
        .target = target,
        .optimize = optimize,
        // The Unix backend calls `dlopen`, which is libc. Nothing in this module
        // is compiled into a linked build, so this costs nothing there.
        .link_libc = true,
    });
}

/// The runtime-loaded `c` module for one target.
///
/// `translate` is the translation step for that same target and configuration;
/// its output is read by the generator, so the dispatch describes the header
/// this build actually selected rather than another one.
pub fn createModule(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Module {
    const core = createCoreModule(b, target, optimize);

    const library = b.createModule(.{
        .root_source_file = b.path("runtime/library.zig"),
        .target = target,
        .optimize = optimize,
    });
    library.addImport("rt", core);

    return createDispatchModule(b, translate, target, optimize, core, library);
}

/// What one generator run writes: the dispatch, and the translation it reads.
const GeneratedSources = struct {
    native: std.Build.LazyPath,
    dispatch: std.Build.LazyPath,
};

fn createDispatchModule(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
    core: *std.Build.Module,
    library: *std.Build.Module,
) *std.Build.Module {
    const sources = generateDispatch(b, translate, target);

    const dispatch = b.createModule(.{
        .root_source_file = sources.dispatch,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    dispatch.addImport("rt", core);
    dispatch.addImport("library", library);

    // The patched translation, under a name that says what it is. Every type
    // and constant in the dispatch is re-exported from here rather than
    // restated, so `c.timezone_t` in a facade and `c_native.timezone_t` in the
    // dispatch are one nominal type - which is what keeps a `timezone_t` a
    // facade opened in one module usable in the other - and `c_routed` is what
    // makes the members nested inside those types the routed wrappers.
    const native = b.createModule(.{
        .root_source_file = sources.native,
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    native.addImport("c_routed", dispatch);
    dispatch.addImport("c_native", native);
    dispatch.addCSourceFiles(.{
        .files = &.{"runtime/sync.c"},
        .flags = &.{b.fmt("-DRT_SYNC_PREFIX={s}", .{sync_prefix})},
        .language = .c,
    });
    return dispatch;
}

/// Runs the generator over the translation step's real output.
///
/// The generator is a host program built and run by this build, so the dispatch
/// is produced for the target being built from that target's own translation.
/// Nothing is cached across configurations: a different header configuration
/// produces a different translation step output, which produces a different
/// dispatch.
fn generateDispatch(
    b: *std.Build,
    translate: *std.Build.Step.TranslateC,
    target: std.Build.ResolvedTarget,
) GeneratedSources {
    const generator = b.addExecutable(.{
        .name = b.fmt("tzdata-runtime-generate-{s}", .{
            target.result.zigTriple(b.allocator) catch @panic("unspellable target"),
        }),
        .root_module = b.createModule(.{
            .root_source_file = b.path("runtime/generate.zig"),
            .target = b.graph.host,
            .optimize = .Debug,
        }),
    });

    const run = b.addRunArtifact(generator);
    run.addArg("--library");
    run.addArg("tzdata");
    run.addArg("--translate");
    run.addFileArg(translate.getOutput());
    if (libc_noise.len != 0) {
        run.addArg("--noise");
        run.addArg(libc_noise);
    }
    if (provider_optional.len != 0) {
        run.addArg("--optional");
        run.addArg(provider_optional);
    }
    if (provider_excluded.len != 0) {
        run.addArg("--exclude");
        run.addArg(provider_excluded);
    }
    run.addArg("--native-output");
    const native_source = run.addOutputFileArg("native.zig");
    run.addArg("--output");
    const dispatch_source = run.addOutputFileArg("dispatch.zig");
    return .{ .native = native_source, .dispatch = dispatch_source };
}