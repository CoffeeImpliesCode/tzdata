//! The build half of tzdata's runtime route: four modules and two generated
//! files.
//!
//! An SDK that ships the runtime route calls `createModule` in place of
//! `translate.createModule()` and imports what comes back as its `c` module.
//! Nothing here links the native library. That is the point: in this
//! configuration the symbols arrive through the platform loader at run time,
//! and linking the archive as well would make the linker demand them before
//! `load` ever runs.
//!
//!   rt        runtime/loader.zig, the reusable core. Pure Zig; imported by the
//!             facade in both configurations, because `LoadSource` and
//!             `LoadError` are this SDK's public types and must be the same
//!             types whichever configuration is built.
//!   library   runtime/library.zig, this SDK's descriptor: the namespaced
//!             synchronization binding and the one load-time check.
//!   dispatch  generated by runtime/generate.zig from the real translation
//!             output: the table, the wrappers, `load`, and the re-exported
//!             translated namespace. It imports `rt`, `library` and the
//!             patched translation as `c_native`.
//!   native    the generator's second file: the same translation with the
//!             `__root` prologue Aro writes replaced by an import of the
//!             dispatch as `c_routed`, so a declaration nested inside a
//!             translated type names the routed wrapper rather than the raw
//!             extern. It imports the dispatch and nothing else.
//!   sync.c    compiled into the dispatch with `-DRT_SYNC_PREFIX=tzdata_rt`, so
//!             its symbols cannot collide with another SDK's.
//!
//! ## The one thing a caller must not do
//!
//! Do not link the compiled C archive into a module that imports this dispatch.
//! The facade's `c` import is the dispatch, and nothing else in the graph should
//! reference the library, or the linker resolves the symbols statically and the
//! runtime route silently becomes a linked one.

const std = @import("std");

/// The prefix `runtime/sync.c` is compiled with.
///
/// `runtime/library.zig` declares the same prefix in the symbol names it binds.
/// The two must agree, and a build where they do not fails to link, which is
/// the whole error report: there is no runtime path that could hide it.
///
/// A build that needs a second, independent instance of this SDK in one binary
/// should change this value *and* the prefix in `runtime/library.zig`, and then
/// give the second instance its own copy of both files. Nothing else in the
/// package assumes one instance.
const sync_prefix = "tzdata_rt";

/// `extern` declarations that are really the C library's, and must stay direct.
///
/// `include/tzdata.h` reaches exactly three C library headers, and it is their
/// declarations - not tzcode's - that dominate what the translation step
/// produces:
///
///   * `<stddef.h>` (`include/tzdata.h:30`) declares no function at all, so it
///     contributes nothing here;
///   * `<time.h>` (`include/tzdata.h:31`) declares the whole of ISO C's
///     `<time.h>`, plus whatever POSIX, XSI, BSD and GNU extensions the target's
///     header set turns on by default. Those are the C library's symbols, and a
///     provider that exports `tz_localtime` does not export `localtime`: this
///     library is built in upstream's `-Dtime_tz=time_t` mode, so every name it
///     defines carries the `tz_` prefix `private.h` puts on it
///     (`private.h:712-789`). Routing any of the unprefixed names would make
///     the load demand libc's own time functions out of libtz, which exports
///     none of them;
///   * `<locale.h>` (`include/tzdata.h:34`), and only where the build set
///     `HAVE_STRFTIME_L`, declares `strftime_l`'s neighbours.
///
/// The list below is a union over every libc family the package can be built
/// for - glibc, musl, wasi-libc, Darwin, FreeBSD, NetBSD, OpenBSD and mingw-w64 -
/// because which of the extensions appear depends on the target's headers and
/// not on anything this file decides.
///
/// A name absent from this list is routed: it goes into the table and the
/// provider is required to export it. So the list is deliberately a superset of
/// what any one target's `<time.h>` declares. Listing a name that never appears
/// costs nothing; omitting one that does makes `load` fail by name.
///
/// The NetBSD block deserves its own note. `generic-netbsd/time.h:196-223`
/// declares, under `_NETBSD_SOURCE`, the *unprefixed* NetBSD names `tzalloc`,
/// `tzfree`, `localtime_rz`, `mktime_z`, `time2posix`, `posix2time`, `timegm`,
/// `timelocal`, `timeoff`, `offtime`, `offtime_r`, `tzgetname` and
/// `tzgetgmtoff`. Those are libc's, not tzcode's, and they are spelled without
/// the `tz_` prefix this library renames everything to, so a NetBSD provider
/// exports `tz_tzalloc` and libc exports `tzalloc`. The `__RENAME` aliases on
/// the same lines (`__tzalloc50` and friends) are listed for the same reason.
///
/// The block was measured rather than reasoned about. On 2026-10-04 the pinned
/// translator was run over `include/tzdata.h` for all 53 published cross-test
