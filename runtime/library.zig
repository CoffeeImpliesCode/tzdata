//! tzdata's side of the runtime loader: the names its synchronization binding
//! has, and what it requires of a provider beyond resolving its symbols.
//!
//! Everything else about the runtime route is generic. `runtime/loader.zig` is
//! the state machine and the platform layer; `runtime/generate.zig` builds the
//! dispatch from whatever the translation step actually produced;
//! `runtime/graph.zig` wires them together. This file is what makes them
//! tzdata's, and it is the file another SDK replaces.
//!
//! ## What a provider must be
//!
//! Every entry point `include/tzdata.h` declares, all of them, in the `tz_`
//! spelling upstream's `-Dtime_tz=time_t` mode produces:
//!
//!   * the NetBSD-inspired reentrant set `tz_tzalloc`, `tz_tzfree`,
//!     `tz_localtime_rz` and `tz_mktime_z` (`private.h:733-735`);
//!   * the X3J11-inspired set `tz_offtime`, `tz_offtime_r`, `tz_timelocal`,
//!     `tz_timeoff`, `tz_posix2time`, `tz_time2posix`, `tz_posix2time_z` and
//!     `tz_time2posix_z` (`private.h:732-751, 758`);
//!   * the POSIX surface `tz_localtime`, `tz_localtime_r`, `tz_gmtime`,
//!     `tz_gmtime_r`, `tz_mktime`, `tz_timegm`, `tz_time` and `tz_tzset`
//!     (`private.h:718-731, 746-757, 764`);
//!   * `tz_ctime`, `tz_asctime`, `tz_difftime` and `tz_strftime`
//!     (`private.h:717, 719-720, 744`);
//!   * `tz_asctime_r`, `tz_ctime_r`, `tz_strftime_l`, `tz_tzname`,
//!     `tz_timezone` and `tz_daylight` where the build selected
//!     `SUPPORT_POSIX2008`, `HAVE_STRFTIME_L`, `HAVE_TZNAME` and `USG_COMPAT`
//!     - see `runtime/graph.zig`, where the reason each is not an *optional*
//!     entry point is spelled out;
//!   * this fork's two linkable accessors for the version strings,
//!     `tzdata_version` and `tzdata_package`. Upstream keeps those in
//!     `version.h` as per-translation-unit `static` arrays
//!     (`localtime.c` never defines them), so nothing can link them and the
//!     fork supplies `src/tzdata_version.c`.
//!
//! The three globals are data, not code: `tz_tzname`, `tz_timezone` and
//! `tz_daylight` are `extern` objects (`localtime.c:623-629`), so the table
//! holds their *addresses* and never a copy. See "Exported data" below.
//!
//! ## The ABI boundary, stated honestly
//!
//! This is a C library with almost no ABI surface of its own, and the
//! interesting requirements are the ones a header cannot state. A provider must
//! be a libtz built by this package's own build graph, for these reasons:
//!
//!   * **`time_t` is signed 64-bit, and the translated header says so.** The
//!     facade refuses to compile against a narrower one (`src/root.zig`), and
//!     `tz_tzalloc`'s `timezone_t` is a `struct state *` whose size and the
//!     `TZ_MAX_TIMES`/`TZ_MAX_TYPES`/`TZ_MAX_CHARS`/`TZ_MAX_LEAPS` bounds in
//!     `tzfile.h` are the sizes this library's `zoneinit` allocates against.
//!   * **`struct tm` is the target's `struct tm`, whatever that is.** Upstream
//!     compiles `TM_GMTOFF` and `TM_ZONE` away where the platform's `<time.h>`
//!     has no `tm_gmtoff`/`tm_zone` (`private.h` reads `NO_TM_GMTOFF` and
//!     `NO_TM_ZONE`, and `build.zig` sets both on mingw-w64 and on every
//!     unknown OS). A provider that *does* define those fields and a dispatch
//!     whose `struct tm` does not is a silent field-by-field mismatch, because
//!     `tz_localtime_rz` writes through a `struct tm *` the caller supplies.
//!     That is exactly what the check below exercises.
//!   * **The four configuration macros above.** They select which declarations
//!     exist at all, so a provider built with different values is a provider
//!     for a different surface. `load` reports that as `MissingSymbol`, by
//!     name.
//!   * **`TZDIR`, the database directory, is compiled into the provider.**
//!     `tzdir.h` is generated by this build and `#define TZDIR` reaches
//!     `localtime.c`, so a plain zone name is resolved below a path *the
//!     provider* was built with. A consumer cannot change it, cannot see it
//!     through this API, and must therefore run with that path present on
//!     disk. `Zone.open` still accepts an absolute path to a TZif file or a
//!     POSIX TZ specification, and both of those need no database at all -
//!     which is what the check below uses, so `load` never depends on the data
//!     being present.
//!   * **The allocator.** `tz_tzalloc` is `malloc(sizeof *sp)`
//!     (`localtime.c:1976`) and `tz_tzfree` is `free(sp)`
//!     (`localtime.c:2005`), through the provider's own allocator. A handle is
//!     released by `tz_tzfree` and by nothing else, exactly once, and the
//!     check below allocates and frees through the provider to prove the
//!     pairing before any caller can get it wrong.
//!   * **The C ABI of the target itself**: scalar widths, calling convention
//!     and the way the platform hands back a function address from `dlsym`.
//!
//! Resolving the symbols and translating the header are the boundary. They are
//! not proof that a provider is compatible, and this file does not pretend to
//! add a version comparison on top. What the check below does is narrower and
//! stronger than a version string: it asks the provider to allocate a zone
//! through `tz_tzalloc`, convert a timestamp through `tz_localtime_rz` and
//! release the handle through `tz_tzfree`, and it reads the converted
//! `struct tm` back through *this* translation's field types. A provider whose
//! `struct tm` layout, `time_t` width, allocator or calling convention differs
//! from the header this build translated does not survive it; a provider that
//! only differs in its version numbers does survive it, which is correct,
//! because tzcode has no versioned ABI.

const rt = @import("rt");
const std = @import("std");

/// The synchronization this loader calls, bound by exact name.
///
/// The names below are `runtime/sync.h` compiled with
/// `RT_SYNC_PREFIX=tzdata_rt`, which is what `runtime/graph.zig` passes. Two
/// spellings of that prefix have to agree: this file names the symbols, and
/// graph.zig defines the macro. A build where they disagree does not link, and
/// that is the whole error report: there is no runtime path that could hide it.
///
/// The core in `runtime/loader.zig` never names a symbol of its own, which is
/// what lets two SDKs, or two configurations of one SDK, hold their own loader
/// state in one process without sharing any of it.
pub const Sync = struct {
    extern fn tzdata_rt_lock() void;
    extern fn tzdata_rt_unlock() void;
    extern fn tzdata_rt_wait() void;
    extern fn tzdata_rt_broadcast() void;
    // `unsigned long long`. Declared as u64, which is the same type in every
    // ABI this SDK targets: 64 bits on x86_64, aarch64, riscv64 and wasm32.
    extern fn tzdata_rt_thread_self() u64;

    pub fn lock() void {
        tzdata_rt_lock();
    }
    pub fn unlock() void {
        tzdata_rt_unlock();
    }
    pub fn wait() void {
        tzdata_rt_wait();
    }
    pub fn broadcast() void {
        tzdata_rt_broadcast();
    }
    pub fn threadSelf() u64 {
        return tzdata_rt_thread_self();
    }
};

/// The loader's configuration for this SDK, given the dispatch that owns the
/// table.
///
/// `dispatch` is the generated module, passed as a type by the dispatch itself
/// so that this file never has to import it. The direction is one-way on
/// purpose: the descriptor knows what the loader needs, the dispatch knows what
/// the header said, and neither imports the other.
pub fn Config(comptime dispatch: type) type {
    return struct {
        /// Named in the pre-load panic, so the message says which library was
        /// reached for before it was loaded.
        pub const library_name = "tzdata";

        /// The table the generated dispatch declares, and the symbols it needs
        /// to fill it. Both come from the translated header, not from this file.
        pub const table = dispatch.Table;
        pub const symbols = dispatch.symbols;
        pub const optional_symbols = dispatch.optional_symbols;

        /// The project's namespaced synchronization binding.
        pub const sync = Sync;

        pub fn tablePtr() *table {
            return dispatch.tablePtr();
        }

        pub fn ready() *rt.Ready {
            return &dispatch.ready;
        }

        pub fn assign(comptime index: usize, dst: *table, address: *const anyopaque) void {
            dispatch.assign(index, dst, address);
        }

        /// One resolved address into one optional table field, and the empty
        /// case beside it. Both index `optional_symbols`, not `symbols`.
        pub inline fn assignOptional(comptime index: usize, dst: *table, address: *const anyopaque) void {
            dispatch.assignOptional(index, dst, address);
        }

        pub inline fn assignMissing(comptime index: usize, dst: *table) void {
            dispatch.assignMissing(index, dst);
        }

        /// The one library-specific check, run after every symbol resolved and
        /// before anything is published.
        ///
        /// It exercises the three reentrant entry points a caller depends on
        /// for ownership, on the one zone that needs no data and no
        /// environment: an **empty** zone name. `zoneinit` takes that branch
        /// before `tzload` (`localtime.c:1808-1819`), installs one rule type at
        /// a zero offset and the abbreviation `UTC`, and reads no file and no
        /// `TZ`. So the check is:
        ///
        ///   * deterministic, and it does not require TZDIR to exist;
        ///   * an allocation made by the *provider* and released by the
        ///     *provider*, which is the `tz_tzalloc`/`tz_tzfree` pairing the
        ///     whole reentrant API rests on;
        ///   * a `time_t` handed to the provider and a `struct tm` filled in by
        ///     the provider and read back through this translation's field
        ///     types, so a layout or width mismatch is caught here rather than
        ///     by the first real conversion.
        ///
        /// The expected values are the calendar, not a version: the epoch is
        /// 1970-01-01T00:00:00, at a zero offset, not in daylight saving time.
        /// That is fixed by the branch it takes, so no database and no calendar
        /// arithmetic is involved.
        pub fn validate(dst: *const table) ?[]const u8 {
            const handle = dst.tz_tzalloc("") orelse
                return "tz_tzalloc(\"\") answered NULL, so this provider cannot " ++
                    "create a zone state at all, and every reentrant conversion " ++
                    "in this API depends on that";
            defer dst.tz_tzfree(handle);

            const epoch: dispatch.time_t = 0;
            var raw: dispatch.struct_tm = std.mem.zeroes(dispatch.struct_tm);
            if (dst.tz_localtime_rz(handle, &epoch, &raw) == null) {
                return "tz_localtime_rz() answered NULL on the empty-name UTC " ++
                    "path, so this provider cannot convert a timestamp";
            }
            if (raw.tm_year != 70 or raw.tm_mon != 0 or raw.tm_mday != 1 or
                raw.tm_hour != 0 or raw.tm_min != 0 or raw.tm_sec != 0 or
                raw.tm_isdst != 0)
            {
                return "tz_localtime_rz() did not answer 1970-01-01T00:00:00 " ++
                    "with tm_isdst 0 on the empty-name UTC path, so this " ++
                    "provider's struct tm layout or time_t width is not the one " ++
                    "these declarations describe";
            }
            // Only where the target's struct tm carries the field: upstream
            // compiles TM_GMTOFF away where the platform's <time.h> has no
            // such member, `private.h` reads NO_TM_GMTOFF, and this build sets
            // it on mingw-w64 and on every unknown OS.
            if (comptime @hasField(dispatch.struct_tm, "tm_gmtoff")) {
                if (raw.tm_gmtoff != 0) {
                    return "tz_localtime_rz() reported a UTC offset other than " ++
                        "zero on the empty-name UTC path, so this provider's " ++
                        "struct tm layout is not the one these declarations " ++
                        "describe";
                }
            }
            return null;
        }
    };
}